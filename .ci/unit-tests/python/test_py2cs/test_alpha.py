from __future__ import annotations
from datetime import datetime, timedelta, timezone
from pathlib import Path
import pytest
from packaging.version import Version
from py2cs.__main__ import main
from py2cs.alpha import alpha_version, read_bhom_version, stamp_version_file

def write_version_file(folder: Path, bhom_version: str = "10.1") -> Path:
    """Writes a _version.py in the form the generator writes it and returns its path.

    The tests of the alpha version use it.
    """
    folder.mkdir(parents=True, exist_ok=True)
    version_file = folder / "_version.py"
    version_file.write_text(
        "# Generated by BHoM_PythonSchema from the BHoM assemblies. Do not edit by hand.\n"
        "# __bhom_version__ is the BHoM version (Major.Minor) of the classes; __version__ is the version of this package.\n\n"
        f'__bhom_version__ = "{bhom_version}"\n'
        f'__version__ = "{bhom_version}.0.dev0"\n',
        encoding="utf-8",
        newline="\n",
    )
    return version_file

def at(day: int, hour: int, minute: int) -> datetime:
    """Returns a UTC time in November 2026.

    The tests of the alpha version use it as the build time.
    """
    return datetime(2026, 11, day, hour, minute, tzinfo=timezone.utc)

def test_the_alpha_version_is_the_bhom_version_with_the_utc_time():
    """Checks that the alpha version is Major.Minor.0a followed by the two-digit year, month, day, hour and minute in UTC.

    Protects the format that users and the workflow rely on.
    """
    assert alpha_version("10.1", [], at(3, 14, 30)) == "10.1.0a2611031430"

def test_the_time_is_taken_in_utc_whatever_the_zone_of_the_clock():
    """Checks that a time with another zone offset is converted to UTC before it is stamped.

    Protects the order of alphas from a runner with a local time zone.
    """
    plus_two = datetime(2026, 11, 3, 14, 30, tzinfo=timezone.utc).astimezone(timezone(timedelta(hours=2)))
    assert alpha_version("10.1", [], plus_two) == "10.1.0a2611031430"

def test_alphas_of_the_same_day_order_by_time_and_stay_below_the_beta():
    """Checks, with the PEP 440 ordering pip uses, that two alphas of one day order by time, that a later day orders after them, and that all are below the beta of the same version and above the previous beta.

    Protects the rule that stable users stay on the beta and alpha users get the newest alpha.
    """
    morning = Version(alpha_version("10.1", ["v10.0.0"], at(3, 6, 0)))
    afternoon = Version(alpha_version("10.1", ["v10.0.0"], at(3, 14, 30)))
    next_day = Version(alpha_version("10.1", ["v10.0.0"], at(4, 6, 0)))

    assert Version("10.0.0") < morning < afternoon < next_day < Version("10.1.0")
    assert all(version.is_prerelease for version in (morning, afternoon, next_day))

def test_an_alpha_of_a_released_bhom_version_fails_and_says_to_bump():
    """Checks that the alpha fails, naming the released tag and the bump, when the tag of its BHoM version exists.

    Protects --pre users from being served an old beta because develop's BHoM version was not bumped after the release.
    """
    with pytest.raises(ValueError, match=r"already released as v10\.0\.0.*Bump the BHoM version"):
        alpha_version("10.0", ["v9.0.0", "v10.0.0"], at(3, 14, 30))

def test_an_older_release_does_not_stop_the_alpha_of_the_next_version():
    """Checks that tags of other versions, and no tags at all, do not stop an alpha.

    Protects the first alpha, and the alpha right after the bump.
    """
    assert alpha_version("10.1", ["v9.0.0", "v10.0.0"], at(3, 6, 0)).startswith("10.1.0a")
    assert alpha_version("10.0", [], at(3, 6, 0)).startswith("10.0.0a")

def test_the_bhom_version_is_read_from_the_version_file(tmp_path: Path):
    """Checks that the BHoM version is read from the generated _version.py and that a file without one is an error.

    Protects the alpha from stamping a version it did not read.
    """
    assert read_bhom_version(write_version_file(tmp_path / "ok", "10.1")) == "10.1"

    empty = tmp_path / "empty"
    empty.mkdir()
    (empty / "_version.py").write_text("__version__ = '1'\n", encoding="utf-8")
    with pytest.raises(ValueError, match="no __bhom_version__"):
        read_bhom_version(empty / "_version.py")

def test_stamping_replaces_only_the_package_version_and_keeps_line_endings(tmp_path: Path):
    """Checks that stamping rewrites the __version__ line, leaves the BHoM version and the comments alone, and keeps the LF line endings.

    Protects the generated file in the alpha's own checkout from other edits.
    """
    version_file = write_version_file(tmp_path)
    stamp_version_file(version_file, "10.1.0a2611031430")

    text = version_file.read_bytes().decode("utf-8")
    assert '__version__ = "10.1.0a2611031430"\n' in text
    assert '__bhom_version__ = "10.1"\n' in text
    assert "dev0" not in text
    assert "\r" not in text

def test_the_command_prints_the_version_and_stamps_only_when_asked(tmp_path: Path, capsys: pytest.CaptureFixture[str]):
    """Checks that the alpha-version command prints the version and leaves the file alone without --stamp, writes it with --stamp, and fails with exit code 2 for a released BHoM version.

    Protects the workflow step that uses the command.
    """
    version_file = write_version_file(tmp_path, "10.1")

    assert main(["alpha-version", "--package", str(tmp_path), "--tags", "v10.0.0"]) == 0
    printed = capsys.readouterr().out.strip()
    assert Version(printed).is_prerelease and printed.startswith("10.1.0a")
    assert "dev0" in version_file.read_text(encoding="utf-8")

    assert main(["alpha-version", "--package", str(tmp_path), "--tags", "v10.0.0", "--stamp"]) == 0
    stamped = capsys.readouterr().out.strip()
    assert f'__version__ = "{stamped}"' in version_file.read_text(encoding="utf-8")

    assert main(["alpha-version", "--package", str(tmp_path), "--tags", "v10.1.0"]) == 2
